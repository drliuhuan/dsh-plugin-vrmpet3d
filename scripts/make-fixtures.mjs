/**
 * Build a minimal but structurally valid PMX 2.0 file in memory.
 *
 * Why a fixture generator instead of committing a .pmx binary: a PMX is a dense,
 * length-prefixed binary format. Committing one would mean any reader of this
 * repo has to trust an opaque blob; generating it here documents the layout and
 * lets the test assert against known vertex/bone/material counts. It also keeps
 * the repo free of third-party model data, which is a licensing constraint for
 * this project (see docs/ASSET-CONTRACT.md).
 *
 * The file produced contains:
 *   - 3 vertices forming one triangle, BDEF1-weighted to bone 0
 *   - 1 bone ("center")
 *   - 1 material
 *   - no textures, no morphs, no rigid bodies, no IK
 */

/** Growable little-endian binary writer. */
export class ByteWriter {
  constructor() {
    this.chunks = [];
    this.length = 0;
  }

  bytes(array) {
    const buffer = Buffer.from(array);
    this.chunks.push(buffer);
    this.length += buffer.length;
    return this;
  }

  u8(value) {
    const b = Buffer.alloc(1);
    b.writeUInt8(value & 0xff, 0);
    return this.bytes(b);
  }

  i8(value) {
    const b = Buffer.alloc(1);
    b.writeInt8(value, 0);
    return this.bytes(b);
  }

  u16(value) {
    const b = Buffer.alloc(2);
    b.writeUInt16LE(value, 0);
    return this.bytes(b);
  }

  i32(value) {
    const b = Buffer.alloc(4);
    b.writeInt32LE(value, 0);
    return this.bytes(b);
  }

  f32(value) {
    const b = Buffer.alloc(4);
    b.writeFloatLE(value, 0);
    return this.bytes(b);
  }

  /** `count` little-endian int32 values. */
  i32Array(values) {
    const b = Buffer.alloc(values.length * 4);
    values.forEach((value, index) => b.writeInt32LE(value, index * 4));
    return this.bytes(b);
  }

  /** `count` little-endian float32 values. */
  f32Array(values) {
    const b = Buffer.alloc(values.length * 4);
    values.forEach((value, index) => b.writeFloatLE(value, index * 4));
    return this.bytes(b);
  }

  /**
   * A PMX text field: int32 byte length followed by bytes in the chosen
   * encoding. PMX 2.0 allows UTF-8 (encoding byte 1) or UTF-16LE (0).
   */
  text(value, encoding) {
    const buffer = encoding === 1 ? Buffer.from(value, 'utf8') : Buffer.from(value, 'utf16le');
    this.i32(buffer.length);
    return this.bytes(buffer);
  }

  toBuffer() {
    return Buffer.concat(this.chunks, this.length);
  }
}

/**
 * @param {object} [options]
 * @param {number} [options.vertexCount] how many vertices to emit (3, 4, …)
 * @param {number} [options.boneCount]
 * @param {boolean} [options.withMorph]
 * @param {number} [options.weightType] 0=BDEF1, 1=BDEF2, 2=BDEF4, 3=SDEF
 * @returns {Buffer} a complete PMX file
 */
export function buildMinimalPmx(options = {}) {
  const vertexCount = Number.isFinite(options.vertexCount) ? options.vertexCount : 3;
  const boneCount = Number.isFinite(options.boneCount) ? options.boneCount : 1;
  const withMorph = options.withMorph === true;
  const weightType = Number.isFinite(options.weightType) ? options.weightType : 0;
  const additionalUvCount = Number.isFinite(options.additionalUvCount) ? options.additionalUvCount : 0;
  const encoding = 1; // UTF-8

  const w = new ByteWriter();

  // --- header ------------------------------------------------------------
  // The six index-size bytes are NOT free-form: each must be exactly 1, 2 or 4,
  // because the reader dispatches on them and throws `unknown number type N` for
  // anything else — including 0. An all-zero header looks tidy and fails
  // immediately. One byte is enough for this fixture's tiny index space.
  w.bytes([0x50, 0x4d, 0x58, 0x20]); // "PMX "
  w.f32(2.0);                        // version
  w.u8(8);                           // header size in bytes (globals follow)
  w.u8(encoding);                    // 0 = UTF-16LE, 1 = UTF-8
  w.u8(additionalUvCount);           // additional UV count
  w.u8(1);                           // vertex index size
  w.u8(1);                           // texture index size
  w.u8(1);                           // material index size
  w.u8(1);                           // bone index size
  w.u8(1);                           // morph index size
  w.u8(1);                           // rigid body index size

  // --- model info --------------------------------------------------------
  w.text('vrmpet3d fixture', encoding);
  w.text('vrmpet3d fixture', encoding);
  w.text('generated by scripts/make-fixtures.mjs', encoding);
  w.text('generated', encoding);

  // --- vertices ----------------------------------------------------------
  w.i32(vertexCount);
  for (let i = 0; i < vertexCount; i++) {
    // Position: a right triangle in the XY plane, ascending in Y.
    w.f32Array([i * 0.1, i * 0.1, 0]);
    w.f32Array([0, 0, 1]);              // normal
    w.f32Array([i / Math.max(1, vertexCount - 1), 0]); // UV, in [0,1]
    for (let extra = 0; extra < additionalUvCount; extra++) w.f32Array([0, 0, 0, 0]);

    w.u8(weightType);
    switch (weightType) {
      case 0: // BDEF1
        w.u8(0); // bone index 0
        break;
      case 1: // BDEF2
        w.u8(0);
        w.u8(boneCount > 1 ? 1 : 0);
        w.f32(1.0);
        break;
      case 2: // BDEF4
        w.u8(0); w.u8(0); w.u8(0); w.u8(0);
        w.f32(1.0); w.f32(0); w.f32(0); w.f32(0);
        break;
      case 3: // SDEF
        w.u8(0);
        w.u8(boneCount > 1 ? 1 : 0);
        w.f32(1.0);
        w.f32Array([0, 0, 0]);
        w.f32Array([0, 0, 0]);
        w.f32Array([0, 0, 0]);
        break;
      default:
        throw new Error('unsupported fixture weight type ' + weightType);
    }
    w.f32(0); // edge scale
  }

  // --- faces -------------------------------------------------------------
  // Indices are 1-based. Vertex index size is 1 byte, so a triangle is 3 bytes;
  // the loader may still read them as int32 depending on its own index handling,
  // which is exactly what this fixture is meant to exercise.
  const faceCount = vertexCount >= 3 ? 1 : 0;
  w.i32(faceCount * 3);
  for (let i = 0; i < faceCount; i++) w.bytes([1, 2, 3]);

  // --- textures ----------------------------------------------------------
  w.i32(0);

  // --- materials ---------------------------------------------------------
  w.i32(1);
  w.text('fixture-material', encoding);
  w.text('fixture-material', encoding);
  w.f32Array([0.8, 0.4, 0.2, 1.0]);    // diffuse
  w.f32Array([0.6, 0.6, 0.6]);         // specular
  w.f32(8);                            // shininess
  w.f32Array([0.2, 0.2, 0.3]);         // ambient
  w.u8(0);                             // draw flag (no double sided / no edge)
  w.f32Array([0.6, 0.6, 0.6, 1.0]);    // edge color
  w.f32(1);                            // edge size
  w.i8(-1);                            // texture index
  w.i8(-1);                            // environment index
  w.u8(0);                             // environment blend mode
  w.u8(0);                             // toon reference (texture)
  w.i8(-1);                            // toon index
  w.text('fixture note', encoding);
  w.i32(faceCount * 3);                // surface count = faceCount * 3 indices

  // --- bones -------------------------------------------------------------
  w.i32(boneCount);
  for (let i = 0; i < boneCount; i++) {
    w.text('center', encoding);
    w.text('center', encoding);
    w.f32Array([i * 0.05, i * 0.10, 0]); // position
    w.u8(-1);                            // parent bone index
    w.i32(0);                            // layer
    w.u16(0x0002);                       // flags: rotatable
    w.i8(-1);                            // tail: no bone
    w.f32Array([0, 0.1, 0]);             // tail offset
    // No move/rotate constraint because the corresponding flags are clear.
  }

  // --- morphs ------------------------------------------------------------
  if (withMorph) {
    w.i32(1);
    w.text('fixture-morph', encoding);
    w.text('fixture-morph', encoding);
    w.u8(1);                             // panel: eyebrow
    w.u8(1);                             // type: vertex morph (1)
    w.i32(1);                            // one offset
    w.u8(0);                             // vertex index 0
    w.f32Array([0, 0.02, 0]);            // translation
  } else {
    w.i32(0);
  }

  // --- display frames ----------------------------------------------------
  w.i32(0);

  // --- rigid bodies ------------------------------------------------------
  w.i32(0);

  // --- joints ------------------------------------------------------------
  w.i32(0);

  // PMX 2.0 optional trailing sections are omitted; a conforming reader stops
  // at the end of the joint list.
  return w.toBuffer();
}
